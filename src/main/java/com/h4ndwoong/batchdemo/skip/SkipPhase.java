package com.h4ndwoong.batchdemo.skip;

/**
 * 행이 스킵된 단계. {@code member_b_error.phase} 에 그대로 저장된다.
 *
 * <p>단계를 기록하는 이유는 <b>사후 재처리 방법이 단계마다 다르기</b> 때문이다. 읽다가 스킵된 행은
 * 원본 자체를 다시 봐야 하고, 가공에서 스킵된 행은 데이터를 고쳐 다시 넣으면 되고, 쓰다가 스킵된
 * 행은 이미 일부가 반영되었을 수 있다. "500건 실패" 보다 "가공 500건 실패" 가 훨씬 쓸모 있는 기록이다.
 */
public enum SkipPhase {

    /**
     * 읽기 단계. 이 실습에서는 발생하지 않는다 — 오염 행도 컬럼 타입은 정상이라 그냥 읽힌다.
     *
     * <p>그래도 기록 경로를 비워 두지 않는 이유는, 리더가 바뀌었을 때(예: 3번 문제의 키셋 페이징)
     * 읽기 실패가 조용히 사라지는 것을 막기 위해서다.
     */
    READ,

    /** 가공(검증) 단계. 2번 문제의 오염 행 500건이 전부 여기서 걸린다. */
    PROCESS,

    /** 쓰기 단계. DB 제약 위반처럼 써 보기 전에는 알 수 없는 실패가 여기 해당한다. */
    WRITE
}
