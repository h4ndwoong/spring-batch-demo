package com.h4ndwoong.batchdemo.outbox;

/**
 * {@code member_g_outbox.status} 의 값. 발송 요청 하나의 일생이다.
 *
 * <p>문자열 리터럴을 SQL 과 자바 여러 곳에 흩어 두지 않기 위한 열거형이다. 6번에서 등급 규칙이
 * 자바와 SQL 두 곳에 존재할 뻔한 것과 같은 종류의 위험이며, 오타 하나로 릴레이가 아무것도 집지
 * 못하는 사고 — <b>그리고 배치는 {@code COMPLETED} 로 끝나는 사고</b> — 를 막는다.
 */
public enum OutboxStatus {

    /** 적재되었으나 아직 나가지 않았다. <b>유실이 아니라 지연</b>이다. */
    PENDING,

    /** 발송되었다. 릴레이가 발송 <em>뒤에</em> 표시하므로, 이 표시가 없다고 안 나간 것은 아니다. */
    SENT,

    /**
     * 발송을 포기했다.
     *
     * <p><b>이 실습은 이 값을 쓰지 않는다.</b> 최소 구현의 릴레이는 발송에 실패하면 예외를 올려
     * 청크를 롤백하고 {@code PENDING} 으로 남긴다 — 다음 실행이 다시 집는다. 이 값과
     * {@code retry_count} / {@code last_error} 컬럼은 재시도 정책(횟수 제한, 백오프, 사후 조치)이
     * 들어올 자리로 비워 둔다. 쓰지 않는 값을 스키마에서 지우지 않는 이유는, <b>재시도 정책 없는
     * Outbox 는 미완성</b>이라는 사실을 스키마가 계속 말하게 하기 위해서다.
     */
    FAILED
}
